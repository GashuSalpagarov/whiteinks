// Страницы услуг /services/<slug>/ (docs/14-service-page.md): один шаблон, components/service/Service.tsx,
// и записи здесь. Новая услуга — новая запись. Цены и сроки — только из прайса (lib/pricing.ts). Тексты
// лёгкие и без обязательств: единственные цифры на странице — из прайса, остальное решает договор.

export type Service = {
  slug: string;
  type: TypeId; // строка прайса: цена и срок; заявка и рисунок — те же, что у клетки в Scene5.tsx
  name: string; // в ряду «Другие услуги»
  h1: string;
  seo: string; // заголовок для выдачи, цена допишется из прайса
  about: string; // описание для выдачи, цена допишется из прайса
  lead: string;
  // Описание под рисунком, без заголовка: что это за услуга и зачем (2–3 коротких предложения), «Подойдёт,
  // если» — 2–3 пункта со строчной буквы, other — когда лучше соседняя услуга, строкой со ссылкой на неё.
  intro: string;
  fits: string[];
  other?: { text: string; slug: string };
  // Примеры — настоящие кейсы, близкие к услуге; нет таких — нет и блока. Название и тип — из works.data.ts,
  // title и kind — своя подпись вместо них, где клиента называть не нужно.
  cases?: { slug: string; text: string; title?: string; kind?: string }[];
  includes: { title: string; text: string }[];
  extra?: string; // что считается отдельно, одной строкой
  steps: { title: string; text: string }[]; // без сроков
  questions: { q: string; a: string }[];
};

const NB = " ";

export const priceRow = (id: TypeId) => TYPES.find((t) => t.id === id) as (typeof TYPES)[number];
