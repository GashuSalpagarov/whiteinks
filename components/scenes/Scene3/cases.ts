export const caseBySlug = (slug: string) => CASES.find((c) => c.slug === slug) ?? null;

export function nextCase(slug: string): CaseData {
  const i = CASES.findIndex((c) => c.slug === slug);
  return CASES[(i + 1) % CASES.length];
}
